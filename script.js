function drawPrompt(kind) {
  if (state.mode !== "truth" || state.currentPrompt) return;
  const availableKinds = getAvailableTruthKinds();
  if (!availableKinds.length) return;
  const resolvedKind =
    kind === "random" ? availableKinds[Math.floor(Math.random() * availableKinds.length)] : kind;
  const deck = getTruthDeck(resolvedKind);
  if (!deck.length) {
    renderTruth();
    return;
  }
  const card = deck[Math.floor(Math.random() * deck.length)];
  state.currentPrompt = { ...card, cardTone: resolvedKind, timerSeconds: 30 };
  promptType.textContent = card.type;
  promptTitle.textContent = card.title;
  promptText.textContent = card.text;
  promptCard.classList.remove("is-dealt");
  void promptCard.offsetWidth;
  promptCard.classList.add("is-dealt");
  addLog(
    state.spiceLevel === "fantasy"
      ? `${getCurrentPlayer().name} 拿到${card.type}：${card.title}。`
      : `${getCurrentPlayer().name} 抽到${card.type}：${card.title}。`,
  );
  setPlayerFeedback(getCurrentPlayer(), "active", card.type);
  showTableToast(`抽到${card.type}`, card.title, "active");
  beginTaskTimer("truth", 30);
  renderTruth();
  scheduleComfortScroll(promptCard);
  scheduleBottomClearance(completePromptButton?.closest(".prompt-actions") || completePromptButton);
}

function completePrompt() {
  if (!state.currentPrompt) return;
  const player = getCurrentPlayer();
  const title = state.currentPrompt.title;
  player.score += 1;
  addLog(`${player.name} 完成：${title}，获得 1 分。`);
  setPlayerFeedback(player, "success", "完成 +1");
  clearPromptCard();
  advancePlayer();
  showTableToast("完成 +1", `${player.name} 完成：${title}`, "success");
  renderTruth();
}

function skipPrompt() {
  if (!state.currentPrompt) return;
  const player = getCurrentPlayer();
  const title = state.currentPrompt.title;
  player.skips += 1;
  addLog(`${player.name} 跳过：${title}。`);
  setPlayerFeedback(player, "skip", "跳过");
  clearPromptCard();
  advancePlayer();
  showTableToast("已跳过", `${player.name} 跳过：${title}`, "skip");
  renderTruth();
}

function nextDdfPrompt() {
  if (state.mode !== "truth") return;
  if (!state.currentPrompt) {
    drawPrompt("dare");
    return;
  }
  const player = getCurrentPlayer();
  const title = state.currentPrompt.title;
  player.skips += 1;
  addLog(`${player.name} 下一题：${title}。`);
  setPlayerFeedback(player, "skip", "下一题");
  clearPromptCard();
  advancePlayer();
  drawPrompt("dare");
}

